#!/usr/bin/env python3
"""Write the bitmap figure of the report as TikZ source.

The glyph data comes from screen_model.py, the same table the independent
screen model uses, so the figure, the model and the RTL all describe the same
bitmaps.  One bitmap cell is drawn as one square; the scaling to 8x8 screen
pixels is shown in the layout figure instead.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import screen_model as model

CELL = 0.15
GAP_HEX = 0.13
HEX_W = 0.62


def glyph(cx, cy, ch):
    """Draw one glyph with its row constants.  (cx, cy) is the lower left."""
    out = []
    x0 = cx
    y0 = cy
    side = 8 * CELL
    rows = model.glyph_rows(ch)
    out.append(r'\fill[black] (%.3f,%.3f) rectangle ++(%.3f,%.3f);' % (x0, y0, side, side))
    for r in range(8):
        for c in range(8):
            if (rows[r] >> (7 - c)) & 1:
                out.append(r'\fill[white] (%.3f,%.3f) rectangle ++(%.3f,%.3f);'
                           % (x0 + c * CELL, y0 + (7 - r) * CELL, CELL, CELL))
    for k in range(9):
        out.append(r'\draw[black,line width=0.12pt,opacity=0.30] (%.3f,%.3f) -- (%.3f,%.3f);'
                   % (x0 + k * CELL, y0, x0 + k * CELL, y0 + side))
        out.append(r'\draw[black,line width=0.12pt,opacity=0.30] (%.3f,%.3f) -- (%.3f,%.3f);'
                   % (x0, y0 + k * CELL, x0 + side, y0 + k * CELL))
    out.append(r'\draw[ink,line width=0.5pt] (%.3f,%.3f) rectangle ++(%.3f,%.3f);'
               % (x0, y0, side, side))
    # row constants
    for r in range(8):
        out.append(r'\node[anchor=west,font=\ttfamily\fontsize{5.2}{6}\selectfont] '
                   r'at (%.3f,%.3f) {%02X};'
                   % (x0 + side + GAP_HEX, y0 + (7 - r) * CELL + CELL / 2.0, rows[r]))
    # label and count
    out.append(r'\node[anchor=north,font=\sffamily\bfseries\fontsize{6.4}{7}\selectfont] '
               r'at (%.3f,%.3f) {%s};'
               % (x0 + side / 2.0, y0 - 0.06, ch))
    ones = sum(bin(r).count('1') for r in rows)
    out.append(r'\node[anchor=north,font=\sffamily\fontsize{4.8}{5.6}\selectfont,'
               r'text=muted] at (%.3f,%.3f) {%d};'
               % (x0 + side / 2.0, y0 - 0.26, ones))
    return out


def main(out):
    L = [r'\begin{tikzpicture}[x=1cm,y=1cm,font=\sffamily\scriptsize]']
    side = 8 * CELL
    step = side + HEX_W + GAP_HEX + 0.42
    # first row: M U S T
    for i, ch in enumerate('MUST'):
        L += glyph(0.10 + i * step, 0.42, ch)
    # second row: E N D
    for i, ch in enumerate('END'):
        L += glyph(0.10 + i * step, -1.55, ch)
    L.append(r'\node[anchor=west,font=\sffamily\fontsize{5.4}{6.4}\selectfont,text=muted] '
             r'at (0.10,-2.55) {Row constants in hexadecimal, row 0 at the top; bit 7 is the '
             r'leftmost pixel, 1 = ink, 0 = background. The number below each glyph is the '
             r'number of 1 bits.};')
    L.append(r'\end{tikzpicture}')
    open(out, 'w').write('%% generated by make_tikz.py\n' + '\n'.join(L) + '\n')
    print('wrote', out)


if __name__ == '__main__':
    dst = sys.argv[1] if len(sys.argv) > 1 else '../../LaTeX/figures/bitmap_cells.tex'
    main(dst)


def screens_figure(out):
    """The three expected screens, to scale, as TikZ."""
    S = 0.00797          # cm per screen pixel
    PW = 640 * S
    PH = 480 * S
    PY = 1.05
    L = [r'\begin{tikzpicture}[x=1cm,y=1cm,font=\sffamily\scriptsize]']
    L.append(r'  \def\s{%.5f}' % S)

    # panel 1: colour bars
    L.append(r'  \begin{scope}[shift={(0,0)}]')
    names = ['red', 'orange', 'yellow', 'green', 'cyan', 'blue', 'magenta',
             'black', 'white', 'gray!65']
    for i, c in enumerate(names):
        L.append(r'    \fill[%s] (%.4f,%.3f) rectangle ++(%.4f,%.3f);'
                 % (c, i * 64 * S, PY, 64 * S, PH))
    L.append(r'    \draw[ink,line width=0.5pt] (0,%.3f) rectangle (%.4f,%.3f);'
             % (PY, PW, PY + PH))
    for i in range(1, 10):
        L.append(r'    \draw[white,line width=0.15pt,opacity=0.55] (%.4f,%.3f) -- ++(0,%.3f);'
                 % (i * 64 * S, PY, PH))
    L.append(r'  \end{scope}')

    # panels 2 and 3: text screens
    for k, (sel, ox) in enumerate([(1, 5.55), (2, 11.10)]):
        L.append(r'  \begin{scope}[shift={(%.3f,0)}]' % ox)
        L.append(r'    \fill[black] (0,%.3f) rectangle (%.4f,%.3f);' % (PY, PW, PY + PH))
        name, x0, letters = model.WORDS[sel]
        for i, ch in enumerate(letters):
            rows = model.glyph_rows(ch)
            for r in range(8):
                for c in range(8):
                    if (rows[r] >> (7 - c)) & 1:
                        x = (x0 + i * model.PITCH + c * 8) * S
                        y = PY + (480 - model.TEXT_Y0 - r * 8 - 8) * S
                        L.append(r'    \fill[white] (%.4f,%.4f) rectangle ++(%.4f,%.4f);'
                                 % (x, y, 8 * S, 8 * S))
        L.append(r'    \draw[ink,line width=0.5pt] (0,%.3f) rectangle (%.4f,%.3f);'
                 % (PY, PW, PY + PH))
        L.append(r'  \end{scope}')

    # panel captions
    caps = [(0, 'BARS', 'screen 0', r'10 bars $\times$ 64 px, full height'),
            (5.55, 'MUST', 'screen 1', r'$x=144,240,336,432$; $y=208\ldots271$'),
            (11.10, 'END', 'screen 2', r'$x=192,288,384$; $y=208\ldots271$')]
    for ox, t, sub, note in caps:
        L.append(r'  \node[font=\fontsize{6.6}{7.8}\selectfont,anchor=north] at (%.3f,%.3f) '
                 r'{\textbf{%s} / %s};' % (ox + PW / 2, PY - 0.10, t, sub))
        L.append(r'  \node[font=\fontsize{5.7}{6.9}\selectfont,text=muted,anchor=north] '
                 r'at (%.3f,%.3f) {%s};' % (ox + PW / 2, PY - 0.42, note))
    # centre line
    L.append(r'  \draw[accent,densely dashed,line width=0.4pt] (0,%.3f) -- (%.3f,%.3f);'
             % (PY + PH / 2, 11.10 + PW + 0.05, PY + PH / 2))
    L.append(r'  \node[font=\fontsize{5.4}{6.6}\selectfont,text=accent,anchor=west] '
             'at (%.3f,%.3f) {$y=239.5$};' % (11.10 + PW + 0.10, PY + PH / 2))
    L.append(r'\end{tikzpicture}')
    open(out, 'w').write('%% generated by make_tikz.py: the three expected screens\n'
                         + '\n'.join(L) + '\n')
    print('wrote', out)
